func TestBivarMultivarColormapUpstreamInventoryIsDocumented(t *testing.T) {
	colors := readUpstreamColorsPy(t)
	upstreamRequired := []string{
		"class MultivarColormap:",
		"def __init__(self, colormaps, combination_mode, name='multivariate colormap'):",
		"_api.check_in_list(['sRGB_add', 'sRGB_sub'], combination_mode=combination_mode)",
		"self.n_variates = len(colormaps)",
		"self._rgba_bad = (0.0, 0.0, 0.0, 0.0)",
		"def __call__(self, X, alpha=None, bytes=False, clip=True):",
		"if len(X) != len(self):",
		"rgba[..., :3] += sub_rgba[..., :3]",
		"rgba[..., 3] *= sub_rgba[..., 3]",
		"if self.combination_mode == 'sRGB_sub':",
		"rgba[mask_bad] = self.get_bad()",
		"if not np.iterable(lutshape) or len(lutshape) != len(self):",
		"class BivarColormap:",
		"def __init__(self, N=256, M=256, shape='square', origin=(0, 0),",
		"_api.check_in_list(['square', 'circle', 'ignore', 'circleignore'], shape=shape)",
		"self._rgba_outside = (1.0, 0.0, 1.0, 1.0)",
		"self.n_variates = 2",
		"def __call__(self, X, alpha=None, bytes=False):",
		"if len(X) != 2:",
		"X0 *= self.N",
		"X1 *= self.M",
		"mask_outside = (X0 < 0) | (X1 < 0) | (X0 >= self.N) | (X1 >= self.M)",
		"rgba = self._lut[X0, X1]",
		"rgba[mask_outside] = self._rgba_outside",
		"rgba[mask_bad] = self._rgba_bad",
		"if np.shape(alpha) not in [(), np.shape(X0)]:",
		"def resampled(self, lutshape, transposed=False):",
		"def __getitem__(self, item):",
		"class SegmentedBivarColormap(BivarColormap):",
		"_api.check_shape((None, None, 3), patch=patch)",
		"_image.resample(_patch, self._lut, transform, _image.BILINEAR,",
		"class BivarColormapFromImage(BivarColormap):",
		"if lut.ndim != 3 or lut.shape[2] not in (3, 4):",
		"if lut.dtype == np.uint8:",
		"new_lut[:, :, 3] = 1.",
	}
	for _, phrase := range upstreamRequired {
		if !strings.Contains(colors, phrase) {
			t.Fatalf("upstream bivar/multivar inventory missing %q", phrase)
		}
	}

	cm := readUpstreamMatplotlibFile(t, "cm.py")
	for _, phrase := range []string{
		"from matplotlib._cm_multivar import cmap_families as multivar_cmaps",
		"from matplotlib._cm_bivar import cmaps as bivar_cmaps",
		"_multivar_colormaps = ColormapRegistry(multivar_cmaps)",
		"_bivar_colormaps = ColormapRegistry(bivar_cmaps)",
	} {
		if !strings.Contains(cm, phrase) {
			t.Fatalf("upstream bivar/multivar registry inventory missing %q", phrase)
		}
	}

	for _, name := range []string{"_cm_bivar.py", "_cm_multivar.py"} {
		data, err := os.ReadFile(filepath.Join("..", "third_party", "matplotlib", "lib", "matplotlib", name))
		if err != nil {
			t.Fatalf("read upstream %s: %v", name, err)
		}
		if !strings.Contains(string(data), "auto-generated by https://github.com/trygvrad/multivariate_colormaps") {
			t.Fatalf("upstream %s missing generated-colormap provenance", name)
		}
	}

	data, err := os.ReadFile(filepath.Join("..", "docs", "matplotlib-migration-notes.md"))
	if err != nil {
		t.Fatalf("read migration notes: %v", err)
	}
	doc := string(data)
	requiredDocs := []string{
		"Phase 17.75.5 Bivar/Multivar Upstream API Inventory",
		"`MultivarColormap`",
		"`combination_mode`",
		"`sRGB_add`",
		"`sRGB_sub`",
		"`BivarColormap`",
		"`square`, `circle`, `ignore`, and `circleignore`",
		"`BivarColormapFromImage` accepts `(N, M, 3)` or `(N, M, 4)` lookup tables",
		"`SegmentedBivarColormap`",
		"`_bivar_colormaps`",
		"`_multivar_colormaps`",
		"scalar-mappable integration is multi-variate",
	}
	for _, phrase := range requiredDocs {
		if !strings.Contains(doc, phrase) {
			t.Fatalf("bivar/multivar inventory docs missing %q", phrase)
		}
	}
}

